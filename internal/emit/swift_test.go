// memberDecl is a member declaration of a generated file: static or
// instance, its name, and its declared type ("" when inferred).
var memberDecl = regexp.MustCompile("(?m)^    public (static let|var) (`?\\w+`?)(?:: ([^={\\n]+?))? *[={]")

// typecheckStub references every member of the generated source src,
// with its declared type, for every value of every axis.
func typecheckStub(t *testing.T, src string) string {
	t.Helper()
	typ := regexp.MustCompile(`(?m)^public struct (\w+): Sendable`).FindStringSubmatch(src)
	require.NotNil(t, typ)
	enums := regexp.MustCompile(`(?m)^    public enum (\w+): String`).FindAllStringSubmatch(src, -1)
	props := regexp.MustCompile(`(?m)^    public var (\w+): (\w+)$`).FindAllStringSubmatch(src, -1)
	require.Len(t, props, len(enums))
	var b strings.Builder
	fmt.Fprintf(&b, "import SwiftUI\n\nfunc useAll() {\n    let _: %[1]s = %[1]s()\n", typ[1])
	var args []string
	for i, p := range props {
		fmt.Fprintf(&b, "    for v%d in %s.%s.allCases {\n", i, typ[1], p[2])
		args = append(args, fmt.Sprintf("%s: v%d", p[1], i))
	}
	fmt.Fprintf(&b, "    let tokens = %s(%s)\n", typ[1], strings.Join(args, ", "))
	for _, p := range props {
		fmt.Fprintf(&b, "    let _: %s.%s = tokens.%s\n", typ[1], p[2], p[1])
	}
	n := 0
	for _, m := range memberDecl.FindAllStringSubmatch(src, -1) {
		recv := "tokens"
		if m[1] == "static let" {
			recv = typ[1]
		}
		name := strings.Trim(m[2], "`")
		if slices.ContainsFunc(props, func(p []string) bool { return p[1] == name }) {
			continue
		}
		decl := strings.TrimSpace(m[3])
		if decl == "" {
			decl = "Color"
		}
		fmt.Fprintf(&b, "    let _: %s = %s.%s\n", qualify(decl, typ[1]), recv, name)
		n++
	}
	require.Positive(t, n)
	b.WriteString(strings.Repeat("    }\n", len(props)) + "}\n")
	return b.String()
}

// qualify spells a member type outside the generated struct.
func qualify(decl, typ string) string {
	for _, nested := range []string{"Bezier", "Shadow"} {
		decl = regexp.MustCompile(`\b`+nested+`\b`).ReplaceAllString(decl, typ+"."+nested)
	}
	return decl
}

// TestSwiftTypechecks: every golden Swift file, with a stub that uses
// every member, typechecks against SwiftUI on macOS.
func TestSwiftTypechecks(t *testing.T) {
	if runtime.GOOS != "darwin" {
		t.Skip("swiftc -typecheck needs macOS's SwiftUI")
	}
	swiftc, err := exec.LookPath("swiftc")
	if err != nil {
		t.Skip("swiftc is not on PATH")
	}
	for path, src := range swiftGoldens(t) {
		t.Run(path, func(t *testing.T) {
			dir := t.TempDir()
			gen, stub := filepath.Join(dir, "DesignTokens.swift"), filepath.Join(dir, "Stub.swift")
			require.NoError(t, os.WriteFile(gen, src, 0o644))
			require.NoError(t, os.WriteFile(stub, []byte(typecheckStub(t, string(src))), 0o644))
			cmd := exec.Command(swiftc, "-typecheck", "-target", "arm64-apple-macos14", gen, stub)
			b, err := cmd.CombinedOutput()
			require.NoError(t, err, "swiftc -typecheck %s:\n%s\nstub:\n%s", path, b, typecheckStub(t, string(src)))
			t.Logf("swiftc -typecheck %s: ok%s", path, strings.TrimRight("\n"+string(b), "\n"))
		})
	}
}
