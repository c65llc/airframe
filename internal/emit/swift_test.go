const sharedSwift = "ios/Shared/DesignTokens.swift"

// perAppOut is where the per-app golden variant of the apple fixture
// writes its Swift files: swift/<app>/DesignTokens.swift.
const perAppOut = "swift/{app}/DesignTokens.swift"

// gutterTokens is a dimension that varies per app, which only a per-app
// Swift file can carry.
const gutterTokens = `{ "gutter": { "$type": "dimension", "$value": { "value": 12, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "semantic", "modes": { "app:tasks": { "value": 16, "unit": "px" } } } } } }`

func swiftOf(t *testing.T, p *project.Project) map[string][]byte {
	t.Helper()
	out, err := Swift(p, applePlatform(t, p))
	require.NoError(t, err)
	return out
}

func appleSwift(t *testing.T) string {
	t.Helper()
	out := swiftOf(t, loadFS(t, os.DirFS(appleDir)))
	require.Equal(t, []string{sharedSwift}, slices.Sorted(maps.Keys(out)))
	return string(out[sharedSwift])
}

// perAppFS is the apple fixture with the Swift file per app and a token,
// gutter, that differs per app.
func perAppFS(t *testing.T) project.MemFS {
	t.Helper()
	fsys := memFS(t, appleDir)
	fsys["airframe.yaml"] = strings.Replace(fsys["airframe.yaml"], "swift: ios/Shared/DesignTokens.swift", "swift: \""+perAppOut+"\"", 1)
	fsys["design-system/tokens/gutter.tokens.json"] = gutterTokens
	return fsys
}

// swiftGoldens is every Swift golden: the fixture's shared file and the
// per-app variant's two files, by path under testdata/apple.
func swiftGoldens(t *testing.T) map[string][]byte {
	t.Helper()
	out := swiftOf(t, loadFS(t, os.DirFS(appleDir)))
	maps.Copy(out, swiftOf(t, loadFS(t, perAppFS(t))))
	return out
}

// TestSwiftGolden: the apple fixture's Swift file, and the per-app
// variant's, equal the committed goldens. -update rewrites them.
func TestSwiftGolden(t *testing.T) {
	out := swiftGoldens(t)
	require.Len(t, out, 3)
	if *update {
		require.NoError(t, os.RemoveAll(filepath.Join(appleDir, "swift")))
		for path, b := range out {
			full := filepath.Join(appleDir, filepath.FromSlash(path))
			require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
			require.NoError(t, os.WriteFile(full, b, 0o644))
		}
	}
	golden := map[string][]byte{}
	require.NoError(t, fs.WalkDir(os.DirFS(appleDir), ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".swift") {
			return err
		}
		b, err := os.ReadFile(filepath.Join(appleDir, filepath.FromSlash(path)))
		golden[path] = b
		return err
	}))
	require.Equal(t, slices.Sorted(maps.Keys(golden)), slices.Sorted(maps.Keys(out)), "run go test ./internal/emit -update")
	for path, b := range out {
		assert.Equal(t, string(golden[path]), string(b), path)
	}
}

func TestSwiftHeaderAndShape(t *testing.T) {
	s := appleSwift(t)
	assert.True(t, strings.HasPrefix(s, "// GENERATED by airframe from design-system/ — do not edit. Regenerate with `airframe build`.\n\nimport SwiftUI\n\n"), s)
	assert.True(t, strings.HasSuffix(s, "}\n"))
	assert.NotContains(t, s, "\r")
	assert.Contains(t, s, "public struct DesignTokens: Sendable {\n")
	assert.Contains(t, s, "    public enum Appearance: String, CaseIterable, Sendable {\n        case light\n        case dark\n    }\n")
	assert.Contains(t, s, "    public enum Density: String, CaseIterable, Sendable {\n        case compact\n        case standard\n        case relaxed\n    }\n")
	assert.Less(t, strings.Index(s, "enum Appearance"), strings.Index(s, "enum Density"), "axis order")
	assert.NotContains(t, s, "enum App:", "the fan-out axis is no parameter")
	assert.NotContains(t, s, "enum Channel", "a fixed axis is no parameter")
}

