// TestSwiftNonColourTypes: one token per row of the type table.
func TestSwiftNonColourTypes(t *testing.T) {
	s := appleSwift(t)
	for _, want := range []string{
		"    public static let space1: CGFloat = 4.0\n",             // dimension, px
		"    public static let radius: CGFloat = 4.0\n",             // dimension, rem × 16
		"    public static let opacityMuted: Double = 0.6\n",        // number
		"    public static let `default`: Double = 1.0\n",           // number, keyword name
		"    public static let durationFast: TimeInterval = 0.15\n", // duration, ms → s
		"    public static let easeStandard: Bezier = Bezier(x1: 0.2, y1: 0.0, x2: 0.0, y2: 1.0)\n",
		"    public static let fontBody: [String] = [\"Inter\", \"system-ui\"]\n",
		"    public static let weightStrong: Font.Weight = .bold\n", // 650 snaps to 700
		"    public static let elevation: [Shadow] = [Shadow(color: Color(\"Tokens/ElevationLayer1\"), x: 0.0, y: 1.0, blur: 2.0, spread: 0.0, inset: false)]\n",
		"    public static let cardShadow: [Shadow] = [Shadow(color: Color(\"Tokens/CardShadowLayer1\"), x: 0.0, y: 1.0, blur: 2.0, spread: 0.0, inset: false)]\n",
	} {
		assert.Contains(t, s, want)
	}
	// A non-colour varying on appearance and density switches on both.
	assert.Contains(t, s, `    public var hairline: CGFloat {
        switch (appearance, density) {
        case (.light, .compact): return 0.5
        case (.light, .standard): return 1.0
        case (.light, .relaxed): return 1.0
        case (.dark, .compact): return 1.0
        case (.dark, .standard): return 1.5
        case (.dark, .relaxed): return 1.5
        }
    }
`)
	assert.Contains(t, s, `    public var gap: CGFloat {
        switch density {
        case .compact: return 4.0
        case .standard: return 4.0
        case .relaxed: return 8.0
        }
    }
`)
	assert.Contains(t, s, "    public struct Bezier: Sendable, Equatable {\n")
	assert.Contains(t, s, "    public struct Shadow: Sendable, Equatable {\n")
}

// TestSwiftShadowAppearance: a shadow whose colour alone changes with
// appearance is static (its colorsets carry the dark colour); one whose
// geometry changes switches on appearance.
func TestSwiftShadowAppearance(t *testing.T) {
	layer := func(y float64) string {
		return fmt.Sprintf(`{ "color": { "colorSpace": "oklch", "components": [0.2, 0, 0], "alpha": 0.2 }, "offsetX": { "value": 0, "unit": "px" }, "offsetY": { "value": %g, "unit": "px" }, "blur": { "value": 2, "unit": "px" }, "spread": { "value": 0, "unit": "px" } }`, y)
	}
	darker := strings.Replace(layer(1), "0.2 }", "0.5 }", 1)
	fsys := memFS(t, appleDir)
	delete(fsys, "design-system/tokens/scale.tokens.json")
	fsys["design-system/tokens/extra.tokens.json"] = `{
  "dim": { "$type": "shadow", "$value": ` + layer(1) + `, "$extensions": { "com.c65llc.airframe": { "tier": "primitive", "modes": { "appearance:dark": ` + darker + ` } } } },
  "lift": { "$type": "shadow", "$value": ` + layer(1) + `, "$extensions": { "com.c65llc.airframe": { "tier": "primitive", "modes": { "appearance:dark": ` + layer(3) + ` } } } } }`
	s := string(swiftOf(t, loadFS(t, fsys))[sharedSwift])
	assert.Contains(t, s, "    public static let dim: [Shadow] = [Shadow(color: Color(\"Tokens/DimLayer1\"), x: 0.0, y: 1.0, blur: 2.0, spread: 0.0, inset: false)]\n")
	assert.Contains(t, s, `    public var lift: [Shadow] {
        switch appearance {
        case .light: return [Shadow(color: Color("Tokens/LiftLayer1"), x: 0.0, y: 1.0, blur: 2.0, spread: 0.0, inset: false)]
        case .dark: return [Shadow(color: Color("Tokens/LiftLayer1"), x: 0.0, y: 3.0, blur: 2.0, spread: 0.0, inset: false)]
        }
    }
`)
	assert.Contains(t, s, "    public init(appearance: Appearance = .light, density: Density = .standard) {\n")
}

