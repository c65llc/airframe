// TestSwiftIdentifierCollision (Review Focus 2): space-4 and space4 both
// camel-case to space4 and are reported, naming both.
func TestSwiftIdentifierCollision(t *testing.T) {
	fsys := memFS(t, appleDir)
	fsys["design-system/tokens/extra.tokens.json"] = `{ "space4": { "$type": "number", "$value": 4,
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } },
  "space": { "4": { "$type": "number", "$value": 4,
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } } } }`
	out, ds := Build(loadFS(t, fsys), []string{"swift"})
	ds = slices.DeleteFunc(ds, func(d diag.Diagnostic) bool { return d.Rule != "emit-failed" })
	require.Len(t, ds, 1, "%v", ds)
	assert.Contains(t, ds[0].Message, `"space-4"`)
	assert.Contains(t, ds[0].Message, `"space4"`)
	assert.Contains(t, ds[0].Message, "space4")
	assert.Empty(t, out)

	// A token that takes an axis's property name collides too.
	fsys = memFS(t, appleDir)
	fsys["design-system/tokens/extra.tokens.json"] = `{ "density": { "$type": "number", "$value": 4,
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } } }`
	_, err := Swift(loadFS(t, fsys), applePlatform(t, loadFS(t, fsys)))
	require.Error(t, err)
	assert.Contains(t, err.Error(), `"density"`)
}

