func xamlPlatform(t *testing.T, p *project.Project) config.Platform {
	t.Helper()
	for _, pl := range p.Config.Platforms {
		if slices.Contains(pl.Emit, "xaml") {
			return pl
		}
	}
	t.Fatal("no xaml platform")
	return config.Platform{}
}

func xamlOf(t *testing.T, p *project.Project) map[string][]byte {
	t.Helper()
	out, err := XAML(p, xamlPlatform(t, p))
	require.NoError(t, err)
	return out
}

// xamlErr is the emit-failed message XAML gives for fsys.
func xamlErr(t *testing.T, fsys fs.FS) string {
	t.Helper()
	p := loadFS(t, fsys)
	_, err := XAML(p, xamlPlatform(t, p))
	require.Error(t, err)
	d := failure(xamlPlatform(t, p), "xaml", err)
	assert.Equal(t, "emit-failed", d.Rule)
	return d.Message
}

// windowsFS is the windows fixture as a MemFS with airframe.yaml rewritten
// by edit.
func windowsFS(t *testing.T, edit func(yaml string) string) project.MemFS {
	t.Helper()
	fsys := memFS(t, windowsDir)
	fsys["airframe.yaml"] = edit(fsys["airframe.yaml"])
	return fsys
}

// xamlGolden checks dir's xaml output against the .xaml goldens under
// dir/windows; -update rewrites them.
func xamlGolden(t *testing.T, dir string, out map[string][]byte) {
	t.Helper()
	if *update {
		require.NoError(t, os.RemoveAll(filepath.Join(dir, "windows")))
		for path, b := range out {
			full := filepath.Join(dir, filepath.FromSlash(path))
			require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
			require.NoError(t, os.WriteFile(full, b, 0o644))
		}
	}
	golden := xamlGoldenFiles(t, dir)
	require.Equal(t, slices.Sorted(maps.Keys(golden)), slices.Sorted(maps.Keys(out)), "run go test ./internal/emit -update")
	for path, b := range out {
		assert.Equal(t, string(golden[path]), string(b), path)
	}
}

func xamlGoldenFiles(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	golden := map[string][]byte{}
	require.NoError(t, fs.WalkDir(os.DirFS(dir), "windows", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".xaml") {
			return err
		}
		b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(path)))
		golden[path] = b
		return err
	}))
	return golden
}

// TestXAMLGolden: both apps' dictionaries and the Default fixture's one
// equal the committed goldens. -update rewrites them.
func TestXAMLGolden(t *testing.T) {
	out := xamlOf(t, loadFS(t, os.DirFS(windowsDir)))
	require.Equal(t, []string{notesXAML, tasksXAML}, slices.Sorted(maps.Keys(out)))
	xamlGolden(t, windowsDir, out)
	def := xamlOf(t, loadFS(t, os.DirFS(xamlDefaultDir)))
	require.Equal(t, []string{defaultXAML}, slices.Sorted(maps.Keys(def)))
	xamlGolden(t, xamlDefaultDir, def)

	notes, tasks := string(out[notesXAML]), string(out[tasksXAML])
	const head = `<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
    <!-- GENERATED by airframe from design-system/ — do not edit. Regenerate with ` + "`airframe build`" + `. -->
`
	for _, f := range []string{notes, tasks, string(def[defaultXAML])} {
		assert.True(t, strings.HasPrefix(f, head), f)
		assert.True(t, strings.HasSuffix(f, "</ResourceDictionary>\n"))
		assert.NotContains(t, f, "\r")
		assert.NotContains(t, f, "\t")
	}
	// accent is per app.
	assert.Contains(t, notes, `<SolidColorBrush x:Key="DesignAccent" Color="#FF3A81D7" />`)
	assert.Contains(t, tasks, `<SolidColorBrush x:Key="DesignAccent" Color="#FF3AA85B" />`)
	assert.Contains(t, notes, `<SolidColorBrush x:Key="DesignAccent" Color="{ThemeResource SystemColorHighlightColor}" />`)
	assert.Contains(t, notes, `<x:Double x:Key="DesignRadius">4</x:Double>`)
	assert.Contains(t, notes, `<x:Double x:Key="DesignDurationFast">150</x:Double>`)
	assert.Contains(t, notes, `<x:Double x:Key="DesignWeightStrong">650</x:Double>`)
	assert.Contains(t, notes, `<KeySpline x:Key="DesignEaseStandard" ControlPoint1="0.2,0" ControlPoint2="0,1" />`)
	assert.Contains(t, notes, `<FontFamily x:Key="DesignFontBody">Inter, system-ui</FontFamily>`)
	assert.Contains(t, notes, `<x:Double x:Key="DesignElevationLayer1OffsetY">1</x:Double>`)
	assert.Contains(t, notes, `<SolidColorBrush x:Key="DesignElevationLayer1" Color="#3312171B" />`)
	assert.NotContains(t, notes, `x:Key="Default"`)

	d := string(def[defaultXAML])
	assert.Contains(t, d, `        <ResourceDictionary x:Key="Default">`)
	assert.NotContains(t, d, "HighContrast")
	assert.Contains(t, d, `<FontFamily x:Key="DesignFontMono">Cascadia Code, Consolas &amp; Co</FontFamily>`)
	assert.Contains(t, d, `<x:Double x:Key="DesignDurationSlow">400</x:Double>`)
	assert.Contains(t, d, `<x:Double x:Key="DesignGap">8</x:Double>`)
	assert.Contains(t, d, `<x:Double x:Key="DesignLiftLayer1Spread">-1</x:Double>`)
	assert.Contains(t, d, `<x:Double x:Key="DesignLiftLayer2Blur">16</x:Double>`)
	// Default repeats the base appearance, light.
	assert.Equal(t, themeDict(t, d, "Light"), strings.Replace(themeDict(t, d, "Default"), `x:Key="Default"`, `x:Key="Light"`, 1))
	assert.NotEqual(t, themeDict(t, d, "Light"), strings.Replace(themeDict(t, d, "Dark"), `x:Key="Dark"`, `x:Key="Light"`, 1))
}

// themeDict is the text of theme dictionary key in a dictionary file.
func themeDict(t *testing.T, file, key string) string {
	t.Helper()
	m := regexp.MustCompile(`(?s)        <ResourceDictionary x:Key="` + key + `">\n.*?        </ResourceDictionary>\n`).FindString(file)
	require.NotEmpty(t, m, key)
	return m
}

// xamlT is what the structure check needs of a test, so a fake can show
// that it fails.
type xamlT interface {
	Errorf(format string, args ...any)
	FailNow()
	Helper()
}

// fakeT records a failure; FailNow panics, for the caller to recover.
type fakeT struct{ failed bool }

func (f *fakeT) Errorf(string, ...any) { f.failed = true }
func (f *fakeT) FailNow()              { f.failed = true; panic(f) }
func (f *fakeT) Helper()               {}

// xamlElem is an element of a parsed dictionary.
type xamlElem struct {
	name     xml.Name
	key      string
	children []*xamlElem
	comments []string
}

const (
	xamlPresentationNS = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
	xamlNS             = "http://schemas.microsoft.com/winfx/2006/xaml"
)

// parseXAML reads b with encoding/xml into an element tree.
func parseXAML(t xamlT, b []byte) *xamlElem {
	t.Helper()
	dec := xml.NewDecoder(strings.NewReader(string(b)))
	var stack []*xamlElem
	var root *xamlElem
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		require.NoError(t, err)
		switch tk := tok.(type) {
		case xml.StartElement:
			e := &xamlElem{name: tk.Name}
			for _, a := range tk.Attr {
				if a.Name.Space == xamlNS && a.Name.Local == "Key" {
					e.key = a.Value
				}
			}
			if len(stack) == 0 {
				require.Nil(t, root, "one root element")
				root = e
				ns := map[string]string{}
				for _, a := range tk.Attr {
					switch {
					case a.Name.Space == "" && a.Name.Local == "xmlns":
						ns[""] = a.Value
					case a.Name.Space == "xmlns":
						ns[a.Name.Local] = a.Value
					}
				}
				assert.Equal(t, map[string]string{"": xamlPresentationNS, "x": xamlNS}, ns)
			} else {
				p := stack[len(stack)-1]
				p.children = append(p.children, e)
			}
			stack = append(stack, e)
		case xml.EndElement:
			stack = stack[:len(stack)-1]
		case xml.Comment:
			if len(stack) > 0 {
				p := stack[len(stack)-1]
				p.comments = append(p.comments, string(tk))
			}
		}
	}
	require.NotNil(t, root)
	return root
}

// checkXAMLStructure checks a dictionary file's structure: the root and
// its namespaces, the header comment, the theme dictionaries holding the
// same keys (brushes, and non-colours varying on appearance), no key twice
// in one dictionary, no themed key at the root, and only x:Double,
// KeySpline and FontFamily there.
func checkXAMLStructure(t xamlT, file string, b []byte) {
	t.Helper()
	root := parseXAML(t, b)
	assert.Equal(t, xml.Name{Space: xamlPresentationNS, Local: "ResourceDictionary"}, root.name, file)
	require.Len(t, root.comments, 1, file)
	assert.True(t, strings.HasPrefix(root.comments[0], " GENERATED by airframe from "), file)

	var themes []*xamlElem
	rootKeys := map[string]bool{}
	for i, c := range root.children {
		if c.name.Local == "ResourceDictionary.ThemeDictionaries" {
			assert.Equal(t, 0, i, "%s: ThemeDictionaries comes first", file)
			assert.Equal(t, xamlPresentationNS, c.name.Space)
			themes = c.children
			continue
		}
		assert.True(t, xamlTyped(c.name), "%s: %v is not x:Double, KeySpline or FontFamily", file, c.name)
		assert.NotEmpty(t, c.key, file)
		assert.False(t, rootKeys[c.key], "%s: key %s twice", file, c.key)
		rootKeys[c.key] = true
	}
	require.Len(t, themes, 3, file)
	var names []string
	var keySets [][]string
	for _, d := range themes {
		assert.Equal(t, xml.Name{Space: xamlPresentationNS, Local: "ResourceDictionary"}, d.name, file)
		names = append(names, d.key)
		seen := map[string]bool{}
		var keys []string
		for _, c := range d.children {
			ok := c.name == xml.Name{Space: xamlPresentationNS, Local: "SolidColorBrush"} || xamlTyped(c.name)
			assert.True(t, ok, "%s: %s holds %v", file, d.key, c.name)
			assert.NotEmpty(t, c.key, file)
			assert.False(t, seen[c.key], "%s: %s holds key %s twice", file, d.key, c.key)
			seen[c.key] = true
			assert.False(t, rootKeys[c.key], "%s: themed key %s also at the root", file, c.key)
			keys = append(keys, c.key)
		}
		assert.NotEmpty(t, keys, file)
		keySets = append(keySets, keys)
	}
	require.Len(t, names, 3)
	assert.Equal(t, []string{"Light", "Dark"}, names[:2], file)
	assert.Contains(t, []string{"HighContrast", "Default"}, names[2], file)
	assert.Equal(t, keySets[0], keySets[1], "%s: Light and Dark keys", file)
	assert.Equal(t, keySets[0], keySets[2], "%s: Light and %s keys", file, names[2])
}

// xamlTyped reports whether name is a non-colour resource element.
func xamlTyped(name xml.Name) bool {
	return name == xml.Name{Space: xamlNS, Local: "Double"} ||
		name == xml.Name{Space: xamlPresentationNS, Local: "KeySpline"} ||
		name == xml.Name{Space: xamlPresentationNS, Local: "FontFamily"}
}

// TestXAMLWellFormed parses every golden with encoding/xml and checks its
// structure.
func TestXAMLWellFormed(t *testing.T) {
	n := 0
	for _, dir := range []string{windowsDir, xamlDefaultDir} {
		for path, b := range xamlGoldenFiles(t, dir) {
			checkXAMLStructure(t, path, b)
			n++
		}
	}
	assert.Equal(t, 3, n)
	// The checker catches what it is for.
	bad := strings.Replace(string(xamlGoldenFiles(t, xamlDefaultDir)[defaultXAML]),
		`        <ResourceDictionary x:Key="Dark">`+"\n",
		`        <ResourceDictionary x:Key="Dark">`+"\n"+`            <SolidColorBrush x:Key="DesignExtra" Color="#FF000000" />`+"\n", 1)
	ft := &fakeT{}
	func() {
		defer func() { _ = recover() }()
		checkXAMLStructure(ft, "bad", []byte(bad))
	}()
	assert.True(t, ft.failed, "a Dark-only brush fails the check")
}

// TestXAMLHighContrastIncomplete: a highContrast mapping that leaves
// colour or shadow tokens out names every one, and one naming a token
// that is not an emitted colour or shadow is an error.
func TestXAMLHighContrastIncomplete(t *testing.T) {
	drop := func(lines ...string) func(string) string {
		return func(y string) string {
			for _, l := range lines {
				require.Contains(t, y, l+"\n")
				y = strings.Replace(y, l+"\n", "", 1)
			}
			return y
		}
	}
	msg := xamlErr(t, windowsFS(t, drop("        ink: SystemColorWindowTextColor", "        elevation: SystemColorWindowTextColor")))
	assert.Equal(t, `platform windows: xaml: highContrast leaves out tokens "elevation", "ink"; map every colour and shadow token to a system colour, or remove highContrast for a Default theme`, msg)

	add := func(line string) func(string) string {
		return func(y string) string {
			return strings.Replace(y, "      highContrast:\n", "      highContrast:\n"+line+"\n", 1)
		}
	}
	msg = xamlErr(t, windowsFS(t, add("        gap: SystemColorWindowTextColor")))
	assert.Equal(t, `platform windows: xaml: highContrast maps token "gap", which is not a colour or shadow token emitted to xaml`, msg)
	msg = xamlErr(t, windowsFS(t, add("        nope: SystemColorWindowTextColor")))
	assert.Contains(t, msg, `highContrast maps token "nope"`)
}

// TestXAMLRuntimeSuffix: a token varying on density gets one resource per
// density value plus the plain key at the base; a colour does so in every
// theme dictionary, and its HighContrast entries share one system colour.
func TestXAMLRuntimeSuffix(t *testing.T) {
	notes := string(xamlOf(t, loadFS(t, os.DirFS(windowsDir)))[notesXAML])
	for _, want := range []string{
		`    <x:Double x:Key="DesignGap">4</x:Double>`,
		`    <x:Double x:Key="DesignGapCompact">4</x:Double>`,
		`    <x:Double x:Key="DesignGapStandard">4</x:Double>`,
		`    <x:Double x:Key="DesignGapRelaxed">8</x:Double>`,
	} {
		assert.Contains(t, notes, want+"\n")
	}
	assert.NotContains(t, notes, "DesignRadiusCompact")
	light, dark, hc := themeDict(t, notes, "Light"), themeDict(t, notes, "Dark"), themeDict(t, notes, "HighContrast")
	for _, k := range []string{"DesignSurface", "DesignSurfaceCompact", "DesignSurfaceStandard", "DesignSurfaceRelaxed"} {
		for _, d := range []string{light, dark} {
			assert.Contains(t, d, `<SolidColorBrush x:Key="`+k+`" Color="#FF`)
		}
		assert.Contains(t, hc, `<SolidColorBrush x:Key="`+k+`" Color="{ThemeResource SystemColorWindowColor}" />`)
	}
	assert.Contains(t, light, `<SolidColorBrush x:Key="DesignSurfaceCompact" Color="#FFDADEE3" />`)
	assert.Contains(t, dark, `<SolidColorBrush x:Key="DesignSurfaceCompact" Color="#FF2A2E33" />`)
	assert.Contains(t, dark, `<SolidColorBrush x:Key="DesignSurface" Color="#FF12171B" />`)
}

// TestXAMLKeys: a key that is not a XAML identifier is an error naming the
// token, a digit after the prefix is fine, and two tokens making one key
// are an error naming both.
func TestXAMLKeys(t *testing.T) {
	const twoXL = `{ "2xl": { "$type": "dimension", "$value": { "value": 24, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } } }`
	fsys := memFS(t, xamlDefaultDir)
	fsys["design-system/tokens/size.tokens.json"] = twoXL
	assert.Contains(t, string(xamlOf(t, loadFS(t, fsys))[defaultXAML]), `    <x:Double x:Key="Design2xl">24</x:Double>`+"\n")

	fsys["airframe.yaml"] += "naming: {xaml: \"{Pascal}\"}\n"
	assert.Equal(t, `platform windows: xaml: token "2xl": xaml naming template "{Pascal}" gives "2xl", which is not a XAML key`, xamlErr(t, fsys))

	fsys = memFS(t, xamlDefaultDir)
	fsys["design-system/tokens/size.tokens.json"] = `{ "tiny": { "$type": "dimension", "$value": { "value": 1, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive", "names": { "xaml": "my-ink" } } } } }`
	assert.Equal(t, `platform windows: xaml: token "tiny": its xaml name "my-ink" is not a XAML key`, xamlErr(t, fsys))

	fsys = memFS(t, xamlDefaultDir)
	fsys["design-system/tokens/size.tokens.json"] = `{ "space-4": { "$type": "dimension", "$value": { "value": 16, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } },
  "wide": { "$type": "dimension", "$value": { "value": 16, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive", "names": { "xaml": "DesignSpace4" } } } } }`
	assert.Equal(t, `platform windows: xaml: tokens "space-4" and "wide" both make XAML key DesignSpace4`, xamlErr(t, fsys))

	// A suffixed key colliding with another token's plain one.
	fsys = memFS(t, xamlDefaultDir)
	fsys["design-system/tokens/size.tokens.json"] = `{ "gap-compact": { "$type": "dimension", "$value": { "value": 2, "unit": "px" },
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive" } } } }`
	assert.Equal(t, `platform windows: xaml: tokens "gap" and "gap-compact" both make XAML key DesignGapCompact`, xamlErr(t, fsys))
}

// TestXAMLGamut: an out-of-gamut OKLCH colour is mapped by CSS Color 4 by
// default and clipped with gamut: clip-srgb, both valid #AARRGGBB.
func TestXAMLGamut(t *testing.T) {
	vivid := color.OKLCH{L: 0.7, C: 0.4, H: 145, Alpha: 1}
	hex := func(r, g, b float64) string {
		c := func(v float64) int { return int(math.Floor(v*255 + 0.5)) }
		return fmt.Sprintf("#FF%02X%02X%02X", c(r), c(g), c(b))
	}
	brush := func(out map[string][]byte) string {
		m := regexp.MustCompile(`<SolidColorBrush x:Key="DesignVivid" Color="(#[0-9A-F]{8})" />`).FindStringSubmatch(themeDict(t, string(out[notesXAML]), "Light"))
		require.NotNil(t, m)
		return m[1]
	}
	clipped := brush(xamlOf(t, loadFS(t, os.DirFS(windowsDir))))
	assert.Equal(t, hex(vivid.ToSRGB(color.Clip)), clipped)
	assert.Equal(t, "#FF00D200", clipped)

	for _, edit := range []func(string) string{
		func(y string) string {
			return strings.Replace(y, "      gamut: clip-srgb\n", "      gamut: css-color-4\n", 1)
		},
		func(y string) string { return strings.Replace(y, "      gamut: clip-srgb\n", "", 1) },
	} {
		mapped := brush(xamlOf(t, loadFS(t, windowsFS(t, edit))))
		assert.Equal(t, hex(vivid.ToSRGB(color.CSSColor4)), mapped)
		assert.Equal(t, "#FF00C300", mapped)
	}
}

// TestXAMLFanOut: with no {app} in the out path there is one file, and a
// token varying per app is an error.
func TestXAMLFanOut(t *testing.T) {
	flat := func(y string) string {
		return strings.Replace(y, `out: "windows/{app}/DesignTokens.xaml"`, `out: "windows/DesignTokens.xaml"`, 1)
	}
	assert.Equal(t, `platform windows: xaml: token "accent" varies per app; put {app} in the xaml out path`, xamlErr(t, windowsFS(t, flat)))

	// Without the per-app tokens it is one file.
	fsys := windowsFS(t, flat)
	fsys["design-system/tokens/semantic.tokens.json"] = strings.Replace(fsys["design-system/tokens/semantic.tokens.json"],
		`"app:tasks": "{green.500}"`, `"density:compact": "{green.500}"`, 1)
	out := xamlOf(t, loadFS(t, fsys))
	assert.Equal(t, []string{"windows/DesignTokens.xaml"}, slices.Sorted(maps.Keys(out)))

	other := func(y string) string {
		return strings.Replace(y, `out: "windows/{app}/DesignTokens.xaml"`, `out: "windows/{channel}/DesignTokens.xaml"`, 1)
	}
	assert.Contains(t, xamlErr(t, windowsFS(t, other)), "has a placeholder that is not the fan-out axis")
}

// TestXAMLAppearanceNonColour: a non-colour token, or a shadow's
// geometry, varying on appearance goes in every theme dictionary, Light
// and Dark at their values and HighContrast or Default at the base, and
// not at the root.
func TestXAMLAppearanceNonColour(t *testing.T) {
	notes := string(xamlOf(t, loadFS(t, os.DirFS(windowsDir)))[notesXAML])
	light, dark, hc := themeDict(t, notes, "Light"), themeDict(t, notes, "Dark"), themeDict(t, notes, "HighContrast")
	for _, want := range []struct {
		key                string
		light, dark, other string
	}{
		{"DesignHairline", "1", "1.5", "1"},
		{"DesignHairlineCompact", "0.5", "1", "0.5"},
		{"DesignHairlineStandard", "1", "1.5", "1"},
		{"DesignHairlineRelaxed", "1", "1.5", "1"},
	} {
		el := func(v string) string { return `            <x:Double x:Key="` + want.key + `">` + v + "</x:Double>\n" }
		assert.Contains(t, light, el(want.light), want.key)
		assert.Contains(t, dark, el(want.dark), want.key)
		assert.Contains(t, hc, el(want.other), want.key)
		assert.NotContains(t, notes, `    <x:Double x:Key="`+want.key+`">`+want.light+"</x:Double>\n    <", "not at the root")
	}
	assert.Equal(t, 3, strings.Count(notes, `x:Key="DesignHairline"`), "once per theme, never at the root")
	// Non-colours that do not vary on appearance stay at the root.
	assert.NotContains(t, light, "DesignGap")
	assert.Contains(t, notes, "\n    <x:Double x:Key=\"DesignGap\">4</x:Double>\n")

	lift := func(darkY int, darkAlpha float64) string {
		return fmt.Sprintf(`{ "$extensions": { "com.c65llc.airframe": { "mode": "appearance:dark" } },
  "lift": { "$value": [ { "color": { "colorSpace": "oklch", "components": [0.2, 0.012, 250], "alpha": %v },
  "offsetX": {"value": 0, "unit": "px"}, "offsetY": {"value": %d, "unit": "px"},
  "blur": {"value": 4, "unit": "px"}, "spread": {"value": -1, "unit": "px"} },
  { "color": { "colorSpace": "oklch", "components": [0.2, 0.012, 250], "alpha": 0.1 },
  "offsetX": {"value": 0, "unit": "px"}, "offsetY": {"value": 8, "unit": "px"},
  "blur": {"value": 16, "unit": "px"}, "spread": {"value": 0, "unit": "px"} } ] } }`, darkAlpha, darkY)
	}
	// Shadow geometry varying on appearance is themed too.
	fsys := memFS(t, xamlDefaultDir)
	fsys["design-system/themes/lift.tokens.json"] = lift(6, 0.25)
	b := xamlOf(t, loadFS(t, fsys))[defaultXAML]
	checkXAMLStructure(t, "lift", b)
	d := string(b)
	assert.Contains(t, themeDict(t, d, "Light"), `            <x:Double x:Key="DesignLiftLayer1OffsetY">2</x:Double>`+"\n")
	assert.Contains(t, themeDict(t, d, "Dark"), `            <x:Double x:Key="DesignLiftLayer1OffsetY">6</x:Double>`+"\n")
	assert.Contains(t, themeDict(t, d, "Default"), `            <x:Double x:Key="DesignLiftLayer1OffsetY">2</x:Double>`+"\n")
	assert.Equal(t, 3, strings.Count(d, `x:Key="DesignLiftLayer2Blur"`))

	// A shadow whose colour alone varies stays geometry-at-the-root.
	fsys["design-system/themes/lift.tokens.json"] = lift(2, 0.5)
	d = string(xamlOf(t, loadFS(t, fsys))[defaultXAML])
	assert.Contains(t, themeDict(t, d, "Light"), `<SolidColorBrush x:Key="DesignLiftLayer1" Color="#4012171B" />`)
	assert.Contains(t, themeDict(t, d, "Dark"), `<SolidColorBrush x:Key="DesignLiftLayer1" Color="#8012171B" />`)
	assert.Equal(t, 1, strings.Count(d, `x:Key="DesignLiftLayer1OffsetY"`))
}

// TestXAMLLayerCountAcrossApps: a shadow whose layer count differs between
// apps is an error saying so.
func TestXAMLLayerCountAcrossApps(t *testing.T) {
	fsys := memFS(t, windowsDir)
	fsys["design-system/tokens/glow.tokens.json"] = `{ "glow": { "$type": "shadow",
  "$value": { "color": { "colorSpace": "oklch", "components": [0.2, 0.01, 250], "alpha": 0.2 },
    "offsetX": { "value": 0, "unit": "px" }, "offsetY": { "value": 1, "unit": "px" },
    "blur": { "value": 2, "unit": "px" }, "spread": { "value": 0, "unit": "px" } },
  "$extensions": { "com.c65llc.airframe": { "tier": "semantic", "modes": { "app:tasks": [
    { "color": { "colorSpace": "oklch", "components": [0.2, 0.01, 250], "alpha": 0.2 },
      "offsetX": { "value": 0, "unit": "px" }, "offsetY": { "value": 1, "unit": "px" },
      "blur": { "value": 2, "unit": "px" }, "spread": { "value": 0, "unit": "px" } },
    { "color": { "colorSpace": "oklch", "components": [0.2, 0.01, 250], "alpha": 0.1 },
      "offsetX": { "value": 0, "unit": "px" }, "offsetY": { "value": 4, "unit": "px" },
      "blur": { "value": 8, "unit": "px" }, "spread": { "value": 0, "unit": "px" } } ] } } } } }`
	fsys["airframe.yaml"] = strings.Replace(fsys["airframe.yaml"], "      highContrast:\n", "      highContrast:\n        glow: SystemColorWindowTextColor\n", 1)
	assert.Equal(t, `platform windows: xaml: token "glow" has 1 shadow layers for app notes and 2 for app tasks; its layer count must be the same across apps, as every app's dictionary holds the same keys`, xamlErr(t, fsys))
}

