var update = flag.Bool("update", false, "rewrite the golden files under testdata/minimal")

// minimalDir is the 2-axis fixture project at the repository root.
var minimalDir = filepath.Join("..", "..", "testdata", "minimal")

const (
	minimalCSS  = "design-system/generated/css/tokens.css"
	minimalJSON = "design-system/generated/json/tokens.json"
)

func loadFS(t testing.TB, fsys fs.FS) *project.Project {
	t.Helper()
	p, ds, err := project.Load(fsys)
	require.NoError(t, err)
	require.Empty(t, ds)
	require.NotNil(t, p)
	return p
}

// buildMinimal builds testdata/minimal, rewriting its golden files first
// when -update is set.
func buildMinimal(t *testing.T) map[string][]byte {
	t.Helper()
	out, ds := Build(loadFS(t, os.DirFS(minimalDir)), nil)
	require.Empty(t, ds)
	if *update {
		for path, b := range out {
			full := filepath.Join(minimalDir, filepath.FromSlash(path))
			require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
			require.NoError(t, os.WriteFile(full, b, 0o644))
		}
	}
	return out
}

func golden(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(minimalDir, filepath.FromSlash(path)))
	require.NoError(t, err, "run go test ./internal/emit -update")
	return b
}

// memFS copies a directory into a MemFS so tests can change it.
func memFS(t testing.TB, dir string) project.MemFS {
	t.Helper()
	m := project.MemFS{}
	require.NoError(t, fs.WalkDir(os.DirFS(dir), ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(path)))
		m[path] = string(b)
		return err
	}))
	return m
}

func TestBuildOutputsAndHeader(t *testing.T) {
	out := buildMinimal(t)
	assert.Equal(t, []string{minimalCSS, minimalJSON}, slices.Sorted(maps.Keys(out)))
	const header = "GENERATED by airframe from design-system/ — do not edit. Regenerate with `airframe build`."
	css := string(out[minimalCSS])
	assert.True(t, strings.HasPrefix(css, "/* "+header+" */\n"), css)
	assert.True(t, strings.HasPrefix(string(out[minimalJSON]), "{\n  \"$comment\": \""+header+"\",\n"))
	for path, b := range out {
		assert.True(t, strings.HasSuffix(string(b), "\n"), path)
		assert.NotContains(t, string(b), "\r", path)
	}
}

func TestBuildFilter(t *testing.T) {
	p := loadFS(t, os.DirFS(minimalDir))
	for _, tc := range []struct {
		filter []string
		want   []string
	}{
		{nil, []string{minimalCSS, minimalJSON}},
		{[]string{"web"}, []string{minimalCSS}},
		{[]string{"css"}, []string{minimalCSS}},
		{[]string{"json"}, []string{minimalJSON}},
		{[]string{"swift"}, nil},
	} {
		out, ds := Build(p, tc.filter)
		require.Empty(t, ds)
		assert.Equal(t, tc.want, slices.Sorted(maps.Keys(out)), "%v", tc.filter)
	}
}

func TestBuildExplicitOut(t *testing.T) {
	fsys := memFS(t, minimalDir)
	fsys["airframe.yaml"] = strings.Replace(fsys["airframe.yaml"], "web: {emit: css}", "web: {emit: css, out: dist/a.css}", 1)
	out, ds := Build(loadFS(t, fsys), []string{"web"})
	require.Empty(t, ds)
	assert.Equal(t, []string{"dist/a.css"}, slices.Sorted(maps.Keys(out)))
}

func TestBuildDeterministic(t *testing.T) {
	p := loadFS(t, os.DirFS(minimalDir))
	first, ds := Build(p, nil)
	require.Empty(t, ds)
	again, _ := Build(p, nil)
	assert.Equal(t, first, again)

	// Re-parse with the token files fed in reverse order.
	slices.Reverse(p.TokenFiles)
	files := map[string][]byte{}
	for _, f := range p.TokenFiles {
		files[f] = p.Sources[f]
	}
	set, tds := tokens.Parse(p.Config, files)
	require.Empty(t, tds)
	p.Tokens = set
	reversed, _ := Build(p, nil)
	require.Equal(t, len(first), len(reversed))
	for path := range first {
		assert.Equal(t, string(first[path]), string(reversed[path]), path)
	}
}

// scopeLine is a line opening a rule block (not an @media block).
var scopeLine = regexp.MustCompile(`(?m)^\s*:root[^{]*\{$`)

func TestBuildEmitsOneBlockPerUsedKey(t *testing.T) {
	p := loadFS(t, testfix.Big576())
	out, err := CSS(p, config.Platform{Name: "web", Emit: []string{"css"}})
	require.NoError(t, err)
	css := string(out["design-system/generated/css/tokens.css"])
	// The 7 used keys plus the default expand to: "" 1, appearance:dark 2,
	// app:tasks 1, app:tasks+appearance:dark 2, channel:next 1,
	// density:compact 1, density:standard 1, density:relaxed 2.
	assert.Len(t, scopeLine.FindAllString(css, -1), 11)
	assert.NotContains(t, css, "data-accent-swatch", "an unused axis emits nothing")
	assert.Equal(t, 3, strings.Count(css, "@media"))
}

func TestSelectorMustStartWithRoot(t *testing.T) {
	fsys := memFS(t, minimalDir)
	fsys["airframe.yaml"] = strings.Replace(fsys["airframe.yaml"], `":root[data-theme='dark']"`, `"html[data-theme='dark']"`, 1)
	out, ds := Build(loadFS(t, fsys), nil)
	require.Len(t, ds, 1)
	assert.Equal(t, "schema-invalid", ds[0].Rule)
	assert.Equal(t, "airframe.yaml", ds[0].File)
	assert.Equal(t, "modes.appearance.web.dark", ds[0].Path)
	assert.Contains(t, ds[0].Message, "appearance:dark")
	assert.NotContains(t, out, minimalCSS)
	assert.Contains(t, out, minimalJSON, "other formats still build")
}

func TestAxisWithoutWebSpelling(t *testing.T) {
	fsys := memFS(t, minimalDir)
	fsys["airframe.yaml"] = strings.Replace(fsys["airframe.yaml"], "web: {attr: data-density, also: {relaxed: \"@media (pointer: coarse)\"}}", "", 1)
	_, ds := Build(loadFS(t, fsys), []string{"css"})
	require.NotEmpty(t, ds)
	assert.Equal(t, "schema-invalid", ds[0].Rule)
	assert.Equal(t, "modes.density.web", ds[0].Path)
	assert.Contains(t, ds[0].Message, "density:compact")
}

func TestEmitListSkipsFormat(t *testing.T) {
	fsys := memFS(t, minimalDir)
	fsys["design-system/tokens/extra.tokens.json"] = `{ "only-json": { "$type": "number", "$value": 3,
  "$extensions": { "com.c65llc.airframe": { "tier": "primitive", "emit": ["json"] } } } }`
	out, ds := Build(loadFS(t, fsys), nil)
	require.Empty(t, ds)
	assert.NotContains(t, string(out[minimalCSS]), "only-json")
	assert.Contains(t, string(out[minimalJSON]), `"only-json"`)
}
