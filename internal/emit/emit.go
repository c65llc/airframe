// Package emit turns a loaded project into its generated outputs: CSS
// custom properties with mode scopes, and a neutral JSON contract. Every
// output is deterministic and byte-stable (LF, final newline, sorted).
package emit

import (
	"errors"
	"fmt"
	"maps"
	"math"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/c65llc/airframe/internal/config"
	"github.com/c65llc/airframe/internal/diag"
	"github.com/c65llc/airframe/internal/project"
	"github.com/c65llc/airframe/internal/tokens"
)

// Emitter writes one format of a platform: repo-relative path → bytes.
type Emitter func(p *project.Project, pl config.Platform) (map[string][]byte, error)

// Emitters maps each emit format to its emitter.
var Emitters = map[string]Emitter{"css": CSS, "json": JSON}

// defaultOut is where a format is written, under the content directory,
// when its platform sets no out.
var defaultOut = map[string]string{
	"css":  "generated/css/tokens.css",
	"json": "generated/json/tokens.json",
}

// configError is airframe.yaml spelling something an emitter cannot use.
// Path locates it in the config.
type configError struct{ path, msg string }

func (e *configError) Error() string { return e.msg }

// Build runs every emitter the filter selects and returns the outputs by
// repo-relative path. A filter entry selects a platform by name (all its
// formats) or a format by name (on every platform); an empty filter selects
// everything. A format with no emitter yet is reported as emit-unsupported
// (a warning) and skipped. A native platform selected by the filter also
// reports each build-bound axis it resolves at its base value
// (emit-axis-fixed, a warning). A failing format is reported and left out;
// the others still build.
func Build(p *project.Project, filter []string) (map[string][]byte, []diag.Diagnostic) {
	out := map[string][]byte{}
	var ds []diag.Diagnostic
	if p == nil || p.Config == nil || p.Tokens == nil {
		return out, nil
	}
	written := map[string]string{} // path → the platform.format that wrote it
	for _, pl := range p.Config.Platforms {
		native := false
		for _, format := range pl.Emit {
			if len(filter) > 0 && !slices.Contains(filter, pl.Name) && !slices.Contains(filter, format) {
				continue
			}
			native = native || slices.Contains(nativeFormats, format)
			em, ok := Emitters[format]
			if !ok {
				// config.Load accepts only known formats, so this is
				// one a later release builds.
				ds = append(ds, diag.Diagnostic{
					Rule: "emit-unsupported", Severity: diag.Warn, File: config.File,
					Path:    "platforms." + pl.Name + ".emit",
					Message: fmt.Sprintf("platform %s: format %s is not built until a later release", pl.Name, format),
					Docs:    diag.DocsURL("emit-unsupported"),
				})
				continue
			}
			files, err := em(p, pl)
			if err != nil {
				ds = append(ds, failure(pl, format, err))
				continue
			}
			for _, f := range slices.Sorted(maps.Keys(files)) {
				by := pl.Name + "." + format
				if prev, dup := written[f]; dup {
					ds = append(ds, diag.Diagnostic{
						Rule: "schema-invalid", Severity: diag.Error, File: config.File,
						Path:    "platforms." + pl.Name + ".out",
						Message: fmt.Sprintf("%s and %s both write %s", prev, by, f),
						Docs:    diag.DocsURL("schema-invalid"),
					})
					continue
				}
				written[f] = by
				out[f] = files[f]
			}
		}
		if native {
			ds = append(ds, PlanNative(p.Config, pl).FixedWarnings(p)...)
		}
	}
	return out, ds
}

func failure(pl config.Platform, format string, err error) diag.Diagnostic {
	if ce, ok := errors.AsType[*configError](err); ok {
		return diag.Diagnostic{
			Rule: "schema-invalid", Severity: diag.Error, File: config.File, Path: ce.path,
			Message: ce.msg, Docs: diag.DocsURL("schema-invalid"),
		}
	}
	return diag.Diagnostic{
		Rule: "emit-failed", Severity: diag.Error, File: config.File, Path: "platforms." + pl.Name,
		Message: fmt.Sprintf("platform %s: %s: %v", pl.Name, format, err),
		Docs:    diag.DocsURL("emit-failed"),
	}
}

// outPath is where pl writes format.
func outPath(p *project.Project, pl config.Platform, format string) string {
	if o := pl.Out[format]; o != "" {
		return o
	}
	return path.Join(p.Config.Content, defaultOut[format])
}

// header is the do-not-edit notice every output carries.
func header(p *project.Project) string {
	return "GENERATED by airframe from " + p.Config.Content + "/ — do not edit. Regenerate with `airframe build`."
}

// emitted lists the tokens that go to format, sorted by name: those with
// no emit list, or whose list names the format.
func emitted(p *project.Project, format string) []*tokens.Token {
	var out []*tokens.Token
	for _, name := range slices.Sorted(maps.Keys(p.Tokens.Tokens)) {
		t := p.Tokens.Tokens[name]
		if len(t.Emit) == 0 || slices.Contains(t.Emit, format) {
			out = append(out, t)
		}
	}
	return out
}

// modeKeys lists the keys that can change t's value: every mode key of a
// token reachable from t through aliases, closed under compatible unions,
// sorted by (pair count, key).
func modeKeys(s *tokens.Set, t *tokens.Token) []config.ModeKey {
	keys := map[config.ModeKey]bool{}
	seen := map[string]bool{t.Name: true}
	for queue := []string{t.Name}; len(queue) > 0; queue = queue[1:] {
		u := s.Tokens[queue[0]]
		if u == nil {
			continue
		}
		vals := []*tokens.Value{u.Default}
		for k, v := range u.Modes {
			keys[k] = true
			vals = append(vals, v)
		}
		for _, v := range vals {
			if v != nil && v.Alias != "" && !seen[v.Alias] {
				seen[v.Alias] = true
				queue = append(queue, v.Alias)
			}
		}
	}
	for grown := true; grown; {
		grown = false
		sorted := slices.SortedFunc(maps.Keys(keys), compareKeys)
		for i, a := range sorted {
			for _, b := range sorted[i+1:] {
				if u, ok := unionKey(a, b); ok && !keys[u] {
					keys[u], grown = true, true
				}
			}
		}
	}
	return slices.SortedFunc(maps.Keys(keys), compareKeys)
}

// unionKey joins two mode keys; ok is false when they set one axis to
// different values.
func unionKey(a, b config.ModeKey) (config.ModeKey, bool) {
	vals := map[string]string{}
	for _, pr := range slices.Concat(pairsOf(a), pairsOf(b)) {
		if prev, ok := vals[pr[0]]; ok && prev != pr[1] {
			return "", false
		}
		vals[pr[0]] = pr[1]
	}
	parts := make([]string, 0, len(vals))
	for _, axis := range slices.Sorted(maps.Keys(vals)) {
		parts = append(parts, axis+":"+vals[axis])
	}
	return config.ModeKey(strings.Join(parts, "+")), true
}

// compareKeys orders mode keys by pair count, then as strings.
func compareKeys(a, b config.ModeKey) int {
	if c := a.Pairs() - b.Pairs(); c != 0 {
		return c
	}
	return strings.Compare(string(a), string(b))
}

// pairsOf splits a mode key into its axis and value pairs, in key order.
func pairsOf(k config.ModeKey) [][2]string {
	if k == "" {
		return nil
	}
	var out [][2]string
	for _, p := range strings.Split(string(k), "+") {
		a, v, _ := strings.Cut(p, ":")
		out = append(out, [2]string{a, v})
	}
	return out
}

// num formats v rounded to 4 decimal places, never as "-0".
func num(v float64) string {
	r := math.Round(v*1e4) / 1e4
	if r == 0 {
		r = 0
	}
	return strconv.FormatFloat(r, 'f', -1, 64)
}
